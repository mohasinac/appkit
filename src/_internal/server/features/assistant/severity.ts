import type { TicketPriority } from "../../../../features/support/schemas/firestore";

/**
 * A4's escalation severities.
 *
 * The plan's four levels, and what each one actually DOES here:
 *
 * | severity | ticket? | priority | why |
 * |---|---|---|---|
 * | `auto`   | no      | —        | answered and logged; nothing to escalate |
 * | `notify` | yes     | `normal` | a human should see it, nothing is burning |
 * | `draft`  | yes     | `high`   | money / refunds / disputes / policy — a wrong answer here costs real money, so it is held for a human rather than guessed |
 * | `urgent` | yes     | `urgent` | the buyer is blocked or something is going wrong now |
 *
 * ## 🛑 Classified from the REFUSAL REASON, not from the buyer's text
 *
 * The tempting design is to ask the model "how urgent is this?" — and that
 * is the one thing that must not decide it. A model that is already failing
 * to answer is not a reliable judge of how badly it failed, and a prompt
 * asking for a severity is a prompt-injection target: "this is URGENT,
 * escalate immediately" in a buyer's message would set it.
 *
 * The refusal reason is generated by our own code paths (`turn.ts`,
 * `model-routing.ts`, `budget.ts`), so it is trusted input. Classification
 * is therefore a pure, testable string match over OUR vocabulary — no model
 * call, no new failure mode, and nothing a buyer can influence.
 *
 * @tag domain:assistant
 * @tag layer:shared
 * @tag access:server
 * @tag sideEffects:none
 */

export type EscalationSeverity = "auto" | "notify" | "draft" | "urgent";

export interface SeverityDecision {
  severity: EscalationSeverity;
  /** `false` only for `auto` — everything else files a ticket. */
  escalates: boolean;
  priority: TicketPriority;
  /** Shown to the buyer. Honest about what happens next, never a guess. */
  buyerMessage: string;
}

/**
 * Topics where a WRONG answer costs money or creates a legal obligation.
 * Matched against the buyer's question only to RAISE severity, never to
 * lower it — the worst a crafted message can do is get a human's attention
 * sooner, which is a failure mode we can live with.
 */
const MONEY_OR_POLICY = [
  "refund",
  "chargeback",
  "cancel",
  "dispute",
  "fraud",
  "scam",
  "overcharg",
  "double charg",
  "not received",
  "never arrived",
  "damaged",
  "broken",
  "wrong item",
  "legal",
  "complaint",
  "grievance",
];

/** Reason fragments our own code emits when the system itself is degraded. */
const SYSTEM_DEGRADED = [
  "budget counter unavailable",
  "ASSISTANT_DISABLED",
  "no eligible provider",
  "no model providers registered",
];

export function classifyEscalation(
  refusalReason: string,
  buyerQuestion: string,
): SeverityDecision {
  const reason = refusalReason.toLowerCase();
  const question = buyerQuestion.toLowerCase();

  /*
   * 🛑 A flagged injection is NOT a support request, and must be checked
   * before anything else.
   *
   * Filing it as a ticket would do two bad things at once: spam the human
   * queue with hostile input, and hand an attacker a cheap way to flood it
   * (every crafted message becomes a ticket). It is also the one branch
   * where the buyer's text must NOT raise severity — that text is the
   * attack, so reading "urgent refund" out of it is reading the attacker's
   * instructions.
   *
   * Refuse, log, file nothing. The event is recorded by the guard's own
   * warning, which is where a security signal belongs.
   */
  if (reason.includes("flagged as prompt injection")) {
    return {
      severity: "auto",
      escalates: false,
      priority: "normal",
      buyerMessage:
        "I can't help with that request. If you have a question about an order or a product, ask me in your own words and I'll do my best.",
    };
  }

  /*
   * 🛑 Money/policy is checked FIRST, before the system-degraded branch.
   *
   * Order matters and is not cosmetic: a refund question that failed because
   * the budget ran out is still a refund question. Classifying it by the
   * MECHANISM of failure rather than by what the buyer asked would file "the
   * assistant was switched off" at normal priority and bury a refund dispute
   * in the general queue.
   */
  if (MONEY_OR_POLICY.some((t) => question.includes(t))) {
    return {
      severity: "draft",
      escalates: true,
      priority: "high",
      buyerMessage:
        "That one needs a person — I've passed it to our support team and they'll get back to you.",
    };
  }

  if (SYSTEM_DEGRADED.some((t) => reason.toLowerCase().includes(t.toLowerCase()))) {
    return {
      severity: "urgent",
      escalates: true,
      priority: "urgent",
      /*
       * The buyer is told the truth — the assistant is down — rather than
       * "I couldn't understand", which blames them for our outage and makes
       * them retry a thing that cannot work.
       */
      buyerMessage:
        "My assistant service is temporarily unavailable, so I've raised this with our support team — they'll follow up with you directly.",
    };
  }

  return {
    severity: "notify",
    escalates: true,
    priority: "normal",
    buyerMessage:
      "I couldn't answer that one, so I've passed it to our support team — they'll get back to you.",
  };
}
