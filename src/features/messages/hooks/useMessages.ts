"use client"
import { useCallback, useMemo, useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { apiClient } from "../../../http/ApiClient";
import { useApiMutation } from "../../../client/api/useApiMutation";
import { MESSAGE_ENDPOINTS } from "../../../constants/api-endpoints";
import { useConversationChannel } from "./useConversationChannel";
import type { ConversationDocument, MessageDocument } from "../schemas/firestore";

interface PagedResult<T> {
  items: T[];
  nextCursor: string | null;
}

/**
 * The inbox list. Bounded (<=50), newest-first — this IS the query the
 * unread badge also sums over, so there is no second "just for the count"
 * query anywhere (D9 spec: "not a second global poll").
 */
export function useConversations(limit = 20, enabled = true) {
  return useQuery<PagedResult<ConversationDocument>>({
    queryKey: ["conversations", limit],
    queryFn: () => apiClient.get(MESSAGE_ENDPOINTS.LIST({ limit })),
    staleTime: 30_000,
    enabled,
  });
}

export function useOpenConversation() {
  return useApiMutation<ConversationDocument, unknown, { otherUserId: string }>({
    mutationFn: ({ otherUserId }) => apiClient.post(MESSAGE_ENDPOINTS.OPEN, { otherUserId }),
    errorMessage: "Could not open the conversation.",
  });
}

/**
 * One thread. Combines the bounded REST page with the RTDB ping channel —
 * a ping triggers `refetch()`, never a client Firestore listener
 * (`firestore.rules` forbids one entirely).
 */
export function useConversationThread(conversationId: string | null) {
  const queryClient = useQueryClient();
  const queryKey = useMemo(() => ["conversation-messages", conversationId], [conversationId]);

  const query = useQuery<PagedResult<MessageDocument>>({
    queryKey,
    queryFn: () => apiClient.get(MESSAGE_ENDPOINTS.THREAD(conversationId!, { limit: 30 })),
    enabled: Boolean(conversationId),
    staleTime: 10_000,
  });

  const getToken = useCallback(
    (id: string) => apiClient.post<{ conversationId: string; customToken: string; expiresAt: number }>(
      MESSAGE_ENDPOINTS.TOKEN(id),
      {},
    ),
    [],
  );

  const onPing = useCallback(() => {
    void queryClient.invalidateQueries({ queryKey });
  }, [queryClient, queryKey]);

  const { error: channelError } = useConversationChannel(conversationId, getToken, onPing);

  return { ...query, channelError };
}

export interface PendingMessage {
  clientMessageId: string;
  body: string;
  status: "pending" | "failed";
}

/**
 * Optimistic send with an explicit pending/failed state and retry — a silent
 * failure is how the old feature hid (D9 spec). `clientMessageId` is a stable
 * uuid generated by the CALLER at compose time (not on each attempt), so a
 * retry reuses the same id and the server resolves it as the same message
 * rather than a duplicate.
 */
export function useSendMessage(conversationId: string) {
  const queryClient = useQueryClient();
  const [pending, setPending] = useState<PendingMessage[]>([]);
  const queryKey = useMemo(() => ["conversation-messages", conversationId], [conversationId]);

  const mutation = useApiMutation<
    MessageDocument,
    unknown,
    { body: string; clientMessageId: string; attachments?: string[]; productId?: string }
  >({
    mutationFn: (vars) => apiClient.post(MESSAGE_ENDPOINTS.THREAD(conversationId), vars),
    onMutate: (vars) => {
      setPending((prev) => [
        ...prev.filter((p) => p.clientMessageId !== vars.clientMessageId),
        { clientMessageId: vars.clientMessageId, body: vars.body, status: "pending" },
      ]);
    },
    onSuccess: (_data, vars) => {
      setPending((prev) => prev.filter((p) => p.clientMessageId !== vars.clientMessageId));
      void queryClient.invalidateQueries({ queryKey });
    },
    onError: (_err, vars) => {
      setPending((prev) =>
        prev.map((p) =>
          p.clientMessageId === vars.clientMessageId ? { ...p, status: "failed" as const } : p,
        ),
      );
    },
    errorMessage: "Message not sent. Tap to retry.",
  });

  const retry = useCallback(
    (p: PendingMessage) => {
      mutation.mutate({ body: p.body, clientMessageId: p.clientMessageId });
    },
    [mutation],
  );

  return { ...mutation, pending, retry };
}

export function useMarkConversationRead() {
  const queryClient = useQueryClient();
  return useApiMutation<{ ok: boolean }, unknown, { conversationId: string }>({
    mutationFn: ({ conversationId }) => apiClient.post(MESSAGE_ENDPOINTS.READ(conversationId), {}),
    onSuccess: () => void queryClient.invalidateQueries({ queryKey: ["conversations"] }),
  });
}

export function useBlockConversation() {
  const queryClient = useQueryClient();
  return useApiMutation<{ ok: boolean }, unknown, { conversationId: string }>({
    mutationFn: ({ conversationId }) => apiClient.post(MESSAGE_ENDPOINTS.BLOCK(conversationId), {}),
    successMessage: "Blocked. They can no longer message you in this conversation.",
    onSuccess: (_d, vars) =>
      void queryClient.invalidateQueries({ queryKey: ["conversation-messages", vars.conversationId] }),
  });
}

/** The nav badge's source when the inbox itself is not mounted — never a
 * second list query of its own. */
export function useUnreadMessageCount(enabled: boolean) {
  return useQuery<{ unread: number }>({
    queryKey: ["messages-unread-count"],
    queryFn: () => apiClient.get(MESSAGE_ENDPOINTS.UNREAD_COUNT),
    staleTime: 60_000,
    enabled,
  });
}
